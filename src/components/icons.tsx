export type IconName = keyof typeof glyphs;

function toPath(rows: readonly string[]) {
  const parts: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let len = 0;
      while (row[x + len] === "#") len++;
      parts.push(`M${x} ${y}h${len}v1h-${len}z`);
      x += len;
    }
  });
  return parts.join("");
}

const paths = Object.fromEntries(
  Object.entries(glyphs).map(([name, rows]) => [name, toPath(rows)]),
) as Record<IconName, string>;

/** 도식(SVG) 안에서 아이콘을 <path>로 직접 그릴 때 쓴다. 16×16 좌표계. */
export const glyphPath = (name: IconName) => paths[name];

type IconProps = Omit<SVGProps<SVGSVGElement>, "name"> & { name: IconName; size?: number };

export function Icon({ name, size = 16, ...rest }: IconProps) {
  return (
    <svg
      data-pixel
      viewBox="0 0 16 16"
      width={size}
      height={size}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      <path d={paths[name]} />
    </svg>
  );
}
